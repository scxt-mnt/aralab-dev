// Scans /templates/*.html and writes src/templates.generated.js so every template shows up in the app
// (picker + live preview) and on the server (AI generation). Files starting with "_" are ignored (examples/drafts).
// Optional first line in a template:  <!-- label: My Template | description: Big bold cards -->
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'templates')
const out = join(root, 'src', 'templates.generated.js')
const BUILTIN = ['classic', 'guide', 'cards']

const pretty = s => s.replace(/[-_]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase())
const result = {}
const files = existsSync(dir) ? readdirSync(dir).filter(f => /\.html?$/i.test(f) && !f.startsWith('_')).sort() : []
for (const f of files) {
  const id = f.replace(/\.html?$/i, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  if (!id) continue
  if (BUILTIN.includes(id)) { console.warn(`[templates] ${f}: "${id}" is a built-in name, rename the file. Skipped.`); continue }
  const html = readFileSync(join(dir, f), 'utf8')
  if (html.length > 300000) { console.warn(`[templates] ${f}: over 300 KB, skipped.`); continue }
  const meta = /<!--\s*([\s\S]*?)-->/.exec(html.slice(0, 600))?.[1] || ''
  const label = /label:\s*([^|]+?)\s*(?:\||$)/i.exec(meta)?.[1]
  const description = /description:\s*([^|]+?)\s*(?:\||$)/i.exec(meta)?.[1]
  result[id] = { label: (label || pretty(id)).trim(), description: (description || 'Custom template').trim(), html }
}
const body = `// AUTO-GENERATED by scripts/generate-templates.mjs from /templates/*.html. Do not edit by hand.\nexport const HTML_TEMPLATES = ${JSON.stringify(result, null, 2)}\n`
writeFileSync(out, body)
console.log(`[templates] ${Object.keys(result).length} custom template(s): ${Object.keys(result).join(', ') || '(none yet, drop .html files into /templates)'}`)
